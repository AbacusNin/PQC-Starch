// Wraps the official CycloneDX schema files in one JavaScript module for the browser. The page's
// Content-Security-Policy blocks network fetches, so JSON files cannot be loaded at run time. The JSON
// files stay the source of truth; a test fails if this module drifts from them.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web', 'schema');
const read = async name => JSON.parse(await fs.readFile(path.join(dir, name), 'utf8'));
const [bom, ...related] = await Promise.all(['bom-1.7.schema.json', 'spdx.schema.json', 'jsf-0.82.schema.json', 'cryptography-defs.schema.json'].map(read));
const body = `// Generated by tools/build-schema-module.mjs from the CycloneDX 1.7.2 schema files in this folder. Do not edit.
export default ${JSON.stringify({bom, related})};
`;
await fs.writeFile(path.join(dir, 'cyclonedx-1.7.js'), body);
console.log(`Wrote web/schema/cyclonedx-1.7.js (${body.length} bytes).`);
