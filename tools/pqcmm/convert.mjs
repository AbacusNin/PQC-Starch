// Converts a PKI Consortium PQC Maturity Model release (YAML) into a module the static site can load without
// a network fetch. It refuses a file whose SHA-256 is missing from, or differs from, the release's SHA256SUMS,
// and a model that fails the release's own JSON Schema.
//
// Usage: node tools/pqcmm/convert.mjs [path/to/pqcmm-model-X.Y.Z.yaml]
// The YAML, the schema, SHA256SUMS, and the license must sit in the same folder, as in tools/pqcmm/source.
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import YAML from 'yaml';
import {createValidator} from '../../web/json-schema.js';

const kit = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = path.resolve(process.argv[2] || path.join(kit, 'tools', 'pqcmm', 'source', 'pqcmm-model-1.0.1.yaml'));
const folder = path.dirname(source);
const fileName = path.basename(source);

export async function convert() {
  const bytes = await fs.readFile(source);
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  const sums = await fs.readFile(path.join(folder, 'SHA256SUMS'), 'utf8');
  const listed = sums.split(/\r?\n/).map(line => line.trim().split(/\s+\*?/)).find(([, name]) => name === fileName)?.[0];
  if (!listed) throw new Error(`${fileName} is not listed in SHA256SUMS.`);
  if (listed !== sha256) throw new Error(`${fileName} does not match SHA256SUMS: expected ${listed}, got ${sha256}.`);
  const schemaName = (await fs.readdir(folder)).find(name => /^pqcmm-model\.schema-.*\.json$/.test(name));
  if (!schemaName) throw new Error('The release schema (pqcmm-model.schema-*.json) is missing.');
  const schema = JSON.parse(await fs.readFile(path.join(folder, schemaName), 'utf8'));
  const model = YAML.parse(bytes.toString('utf8'));
  const errors = createValidator(schema)(model);
  if (errors.length) throw new Error(`The model fails ${schemaName}: ${errors.slice(0, 3).map(error => `${error.path} ${error.message}`).join('; ')}`);
  const version = model.model.version;
  const data = {
    provenance:{publisher:'PKI Consortium', release:`v${version}`, file:fileName, sha256, schema:schemaName, license:'MIT', copyright:'Copyright (c) 2022 PKI Consortium',
      url:`https://github.com/pkic/pqcmm/releases/tag/v${version}`},
    schema, model
  };
  const out = path.join(kit, 'web', 'data', `pqcmm-${version}.js`);
  await fs.mkdir(path.dirname(out), {recursive:true});
  await fs.writeFile(out, `// Generated by tools/pqcmm/convert.mjs from ${fileName} (PKI Consortium, MIT license; see LICENSE.PQCMM.txt). Do not edit.\nexport default ${JSON.stringify(data)};\n`);
  await fs.copyFile(path.join(folder, 'LICENSE.PQCMM.txt'), path.join(kit, 'web', 'data', 'LICENSE.PQCMM.txt'));
  return {out, sha256, criteria:model.levels.reduce((sum, level) => sum + (level.criteria?.items?.length || 0), 0)};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await convert();
  console.log(`Wrote ${path.relative(kit, result.out)}: ${result.criteria} criteria, sha256 ${result.sha256}.`);
}
