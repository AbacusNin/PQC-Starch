// Builds a CycloneDX 1.7 CBOM from the reviewer's manual crypto map. The file carries the same unsigned-draft
// marker as the claim drafts, plus a source property saying it was typed in, not discovered by scanning.
// Only what the reviewer entered is written: no algorithm primitive is inferred, and owner names stay out.
import {DRAFT_STATUS} from './attestation.js';

const SOURCE = 'Manual crypto map entered by a reviewer in the PQC Buyer Workbook. Not generated by scanning the product; coverage is only what the reviewer recorded.';
const ASSET_TYPES = new Set(['algorithm', 'certificate', 'protocol', 'related-crypto-material']);
const filled = value => Boolean(String(value ?? '').trim());
const slug = value => String(value).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'item';

function protocolType(version) {
  const value = String(version || '').toLowerCase();
  if (value.includes('dtls')) return 'dtls';
  if (value.includes('quic')) return 'quic';
  if (value.includes('tls')) return 'tls';
  if (value.includes('ssh')) return 'ssh';
  if (value.includes('ike')) return 'ike';
  if (value.includes('ipsec')) return 'ipsec';
  return 'unknown';
}

function assetType(use) {
  const value = String(use.assetType || '').toLowerCase().replace(/\s+/g, '-');
  return ASSET_TYPES.has(value) ? value : 'algorithm';
}

const property = (name, value) => filled(value) ? [{name:`pqc-buyer-workbook:${name}`, value:String(value)}] : [];

export function buildCbomDraft(state, serialNumber) {
  const buyer = state.buyer || {};
  const uses = (state.crypto || []).filter(use => filled(use.current));
  const skipped = (state.crypto || []).filter(use => !filled(use.current)).map(use => use.id);
  const assets = new Map();
  const software = new Map();
  const provides = new Map();
  for (const use of uses) {
    const ref = filled(use.cbomRef) ? use.cbomRef.trim() : `asset-${slug(use.id)}`;
    if (!assets.has(ref)) {
      const type = assetType(use);
      const cryptoProperties = {assetType:type};
      if (type === 'algorithm' && filled(use.parameter)) cryptoProperties.algorithmProperties = {parameterSetIdentifier:use.parameter};
      if (type === 'protocol') cryptoProperties.protocolProperties = {type:protocolType(use.protocolVersion), ...(filled(use.protocolVersion) ? {version:use.protocolVersion} : {}),
        ...(filled(use.cipherSuite) ? {cipherSuites:[{name:use.cipherSuite}]} : {})};
      assets.set(ref, {type:'cryptographic-asset', 'bom-ref':ref, name:use.current.trim(), cryptoProperties, uses:[]});
    }
    assets.get(ref).uses.push(use);
    if (filled(use.component) || filled(use.componentPurl)) {
      const key = `${use.component}|${use.componentPurl}`;
      if (!software.has(key)) software.set(key, {type:'library', 'bom-ref':`component-${software.size + 1}`, name:(use.component || use.componentPurl).trim(), ...(filled(use.componentPurl) ? {purl:use.componentPurl.trim()} : {})});
      const owner = software.get(key)['bom-ref'];
      provides.set(owner, [...new Set([...(provides.get(owner) || []), ref])]);
    }
  }
  const components = [...software.values(), ...[...assets.values()].map(({uses: entries, ...asset}) => ({...asset, properties:[
    ...property('crypto-use-ids', entries.map(use => use.id).join(', ')),
    ...property('protects', [...new Set(entries.map(use => use.protected).filter(filled))].join('; ')),
    ...property('function', [...new Set(entries.map(use => use.function).filter(filled))].join('; ')),
    ...property('path', [...new Set(entries.map(use => use.path).filter(filled))].join('; ')),
    ...property('source-node', [...new Set(entries.map(use => use.sourceNode).filter(filled))].join('; ')),
    ...property('destination-node', [...new Set(entries.map(use => use.destinationNode).filter(filled))].join('; ')),
    ...property('trust-boundary', [...new Set(entries.map(use => use.trustBoundary).filter(filled))].join('; ')),
    ...property('usage-status', [...new Set(entries.map(use => use.usageStatus).filter(filled))].join('; ')),
    ...property('coverage', [...new Set(entries.map(use => use.coverage).filter(filled))].join('; ')),
    ...property('pqc-target', [...new Set(entries.map(use => use.target).filter(filled))].join('; '))
  ]}))];
  const dependencies = [
    {ref:'product', dependsOn:[...software.values()].map(item => item['bom-ref'])},
    ...[...provides.entries()].map(([ref, assetRefs]) => ({ref, provides:assetRefs}))
  ];
  const cbom = {
    $schema:'http://cyclonedx.org/schema/bom-1.7.schema.json',
    bomFormat:'CycloneDX', specVersion:'1.7', serialNumber, version:1,
    metadata:{timestamp:new Date().toISOString(),
      tools:{components:[{type:'application', name:'PQC Buyer Workbook'}]},
      component:{type:'application', 'bom-ref':'product', name:buyer.product || 'Unspecified product', ...(filled(buyer.version) ? {version:buyer.version} : {})},
      properties:[{name:'pqc-buyer-workbook:document-status', value:DRAFT_STATUS}, {name:'pqc-buyer-workbook:signed', value:'false'}, {name:'pqc-buyer-workbook:source', value:SOURCE}]},
    components,
    dependencies
  };
  return {cbom, skipped};
}
